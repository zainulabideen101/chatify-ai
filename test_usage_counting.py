"""Test daily usage counting and over-limit AI suppression.

This test verifies:
1. Daily usage service counts one customer phone once per Asia/Karachi day
2. Over-limit customers are marked AI-disallowed but still storable
3. No customer-facing outbound message is generated by the limit branch
"""
import asyncio
import os
import sys
from datetime import datetime
from zoneinfo import ZoneInfo
from bson import ObjectId

# Add backend to path and load environment
sys.path.insert(0, '/app/backend')
from dotenv import load_dotenv
load_dotenv('/app/backend/.env')

from database import db
from services.billing import record_unique_chat, get_usage_summary, day_key


async def test_usage_counting():
    """Test that usage counting works correctly."""
    print("\n=== Testing Daily Usage Counting ===")
    
    # Get a test merchant
    merchant = await db.merchants.find_one({})
    if not merchant:
        print("❌ No merchant found in database")
        return False
    
    merchant_id = str(merchant["_id"])
    print(f"✅ Using merchant: {merchant_id}")
    
    # Get current day
    today = day_key()
    pkt_today = datetime.now(ZoneInfo("Asia/Karachi")).date().isoformat()
    
    if today != pkt_today:
        print(f"❌ day_key() returned {today}, expected {pkt_today}")
        return False
    else:
        print(f"✅ day_key() returns Asia/Karachi date: {today}")
    
    # Test phone numbers
    test_phone_1 = "+92 300 9999991"
    test_phone_2 = "+92 300 9999992"
    
    # Clear any existing test data
    await db.daily_chat_usage.delete_many({
        "merchant_id": ObjectId(merchant_id),
        "customer_phone": {"$in": [test_phone_1, test_phone_2]}
    })
    
    # Get initial usage
    initial_summary = await get_usage_summary(merchant_id)
    initial_used = initial_summary["used"]
    print(f"✅ Initial usage: {initial_used}/{initial_summary['limit']}")
    
    # Record first chat for phone 1
    result1 = await record_unique_chat(merchant_id, test_phone_1)
    if not result1["is_new_chat"]:
        print(f"❌ First chat should be new, got is_new_chat={result1['is_new_chat']}")
        return False
    if not result1["ai_allowed"]:
        print(f"❌ First chat should allow AI, got ai_allowed={result1['ai_allowed']}")
        return False
    print(f"✅ First chat for {test_phone_1}: is_new_chat=True, ai_allowed=True")
    
    # Record second chat for same phone (should not increment)
    result2 = await record_unique_chat(merchant_id, test_phone_1)
    if result2["is_new_chat"]:
        print(f"❌ Second chat for same phone should not be new, got is_new_chat={result2['is_new_chat']}")
        return False
    if result2["used"] != result1["used"]:
        print(f"❌ Usage should not increment for same phone, got {result2['used']} vs {result1['used']}")
        return False
    print(f"✅ Second chat for {test_phone_1}: is_new_chat=False, usage unchanged")
    
    # Record chat for different phone
    result3 = await record_unique_chat(merchant_id, test_phone_2)
    if not result3["is_new_chat"]:
        print(f"❌ Chat for new phone should be new, got is_new_chat={result3['is_new_chat']}")
        return False
    if result3["used"] != result1["used"] + 1:
        print(f"❌ Usage should increment for new phone, got {result3['used']} vs expected {result1['used'] + 1}")
        return False
    print(f"✅ First chat for {test_phone_2}: is_new_chat=True, usage incremented")
    
    # Verify final usage
    final_summary = await get_usage_summary(merchant_id)
    expected_used = initial_used + 2
    if final_summary["used"] != expected_used:
        print(f"❌ Final usage should be {expected_used}, got {final_summary['used']}")
        return False
    print(f"✅ Final usage: {final_summary['used']}/{final_summary['limit']}")
    
    # Clean up
    await db.daily_chat_usage.delete_many({
        "merchant_id": ObjectId(merchant_id),
        "customer_phone": {"$in": [test_phone_1, test_phone_2]}
    })
    
    return True


async def test_over_limit_behavior():
    """Test that over-limit customers are marked AI-disallowed but still storable."""
    print("\n=== Testing Over-Limit AI Suppression ===")
    
    # Create a test merchant with a low limit
    test_merchant_id = ObjectId()
    await db.merchants.insert_one({
        "_id": test_merchant_id,
        "store_name": "Test Limit Store",
        "currency": "PKR",
        "created_at": datetime.now(ZoneInfo("UTC")).isoformat()
    })
    
    # Set to free plan (limit 15)
    from services.billing import ensure_subscription
    await ensure_subscription(test_merchant_id)
    
    merchant_id = str(test_merchant_id)
    today = day_key()
    
    # Fill up to the limit
    for i in range(15):
        phone = f"+92 300 8888{i:03d}"
        result = await record_unique_chat(merchant_id, phone)
        if not result["ai_allowed"]:
            print(f"❌ Chat {i+1}/15 should allow AI, got ai_allowed={result['ai_allowed']}")
            await cleanup_test_merchant(test_merchant_id)
            return False
    
    print(f"✅ First 15 chats allowed AI")
    
    # 16th chat should be stored but AI disallowed
    over_limit_phone = "+92 300 8888999"
    result = await record_unique_chat(merchant_id, over_limit_phone)
    
    if not result["is_new_chat"]:
        print(f"❌ Over-limit chat should still be new, got is_new_chat={result['is_new_chat']}")
        await cleanup_test_merchant(test_merchant_id)
        return False
    
    if result["ai_allowed"]:
        print(f"❌ Over-limit chat should not allow AI, got ai_allowed={result['ai_allowed']}")
        await cleanup_test_merchant(test_merchant_id)
        return False
    
    print(f"✅ 16th chat: is_new_chat=True, ai_allowed=False (correctly suppressed)")
    
    # Verify the chat was stored
    stored = await db.daily_chat_usage.find_one({
        "merchant_id": test_merchant_id,
        "day": today,
        "customer_phone": over_limit_phone
    })
    
    if not stored:
        print(f"❌ Over-limit chat should be stored in database")
        await cleanup_test_merchant(test_merchant_id)
        return False
    
    if stored.get("ai_allowed") != False:
        print(f"❌ Stored chat should have ai_allowed=False, got {stored.get('ai_allowed')}")
        await cleanup_test_merchant(test_merchant_id)
        return False
    
    print(f"✅ Over-limit chat stored with ai_allowed=False")
    
    # Verify summary shows over limit
    summary = await get_usage_summary(merchant_id)
    if summary["used"] != 16:
        print(f"❌ Summary should show 16 used, got {summary['used']}")
        await cleanup_test_merchant(test_merchant_id)
        return False
    
    if summary["ai_available_for_new_chats"]:
        print(f"❌ Summary should show AI not available, got {summary['ai_available_for_new_chats']}")
        await cleanup_test_merchant(test_merchant_id)
        return False
    
    print(f"✅ Summary correctly shows: used={summary['used']}, limit={summary['limit']}, ai_available=False")
    
    # Clean up
    await cleanup_test_merchant(test_merchant_id)
    
    return True


async def cleanup_test_merchant(merchant_id):
    """Clean up test merchant data."""
    await db.merchants.delete_one({"_id": merchant_id})
    await db.billing_subscriptions.delete_one({"merchant_id": merchant_id})
    await db.daily_chat_usage.delete_many({"merchant_id": merchant_id})


async def test_webhook_enforcement():
    """Test that webhook handler respects the ai_allowed flag."""
    print("\n=== Testing Webhook AI Enforcement ===")
    
    # This test verifies the logic in integrations.py webhook handler
    # The handler checks usage["ai_allowed"] and skips AI reply if False
    
    # Get the webhook handler code
    import inspect
    from routers.integrations import _process_whatsapp_inbound
    
    source = inspect.getsource(_process_whatsapp_inbound)
    
    # Check for the enforcement logic
    if 'usage = await record_unique_chat' in source:
        print("✅ Webhook handler calls record_unique_chat")
    else:
        print("❌ Webhook handler does not call record_unique_chat")
        return False
    
    if 'if not usage["ai_allowed"]' in source or 'if not usage.get("ai_allowed")' in source:
        print("✅ Webhook handler checks ai_allowed flag")
    else:
        print("❌ Webhook handler does not check ai_allowed flag")
        return False
    
    if 'needs_attention' in source and 'daily_chat_limit' in source:
        print("✅ Webhook handler marks conversation as needs_attention when over limit")
    else:
        print("⚠️  Webhook handler may not properly mark over-limit conversations")
    
    # Check that no customer-facing message is sent
    if 'continue' in source:
        print("✅ Webhook handler uses 'continue' to skip AI reply (no customer-facing message)")
    else:
        print("⚠️  Webhook handler may not skip AI reply properly")
    
    return True


async def main():
    """Run all usage counting tests."""
    print("="*80)
    print("DAILY USAGE COUNTING & OVER-LIMIT AI SUPPRESSION TESTS")
    print("="*80)
    
    results = []
    
    # Test basic usage counting
    results.append(await test_usage_counting())
    
    # Test over-limit behavior
    results.append(await test_over_limit_behavior())
    
    # Test webhook enforcement
    results.append(await test_webhook_enforcement())
    
    print("\n" + "="*80)
    print("TEST SUMMARY")
    print("="*80)
    passed = sum(results)
    total = len(results)
    print(f"PASSED: {passed}/{total}")
    print("="*80 + "\n")
    
    return all(results)


if __name__ == "__main__":
    success = asyncio.run(main())
    sys.exit(0 if success else 1)
